func GetBrandNameByID(id string) string {
	for _, brand := range BrandData {
		if brand["_id"] == id {
			if name, ok := brand["name"].(string); ok {
				return name
			}
		}
	}
	return ""
}

func GetServiceNameByID(id string) string {
	for _, service := range ServicesData {
		if service["_id"] == id {
			if name, ok := service["name"].(string); ok {
				return name
			}
		}
	}
	return ""
}

func GetBrandNamesByIDs(ids []string) []string {
	var names []string
	for _, id := range ids {
		name := GetBrandNameByID(id)
		if name != "" {
			names = append(names, name)
		}
	}
	return names
}

